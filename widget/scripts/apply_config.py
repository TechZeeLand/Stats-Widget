"""Turns config.toml into the files eww needs:
  window.yuck  where the window goes and how big it is
  theme.scss   background opacity and the scale factors
  eww.yuck     the layout, rendered from eww.yuck.in for the chosen size"""
import re

from common import (ANCHORS, DEFAULT_H, DEFAULT_W, LAYERS, ROOT, config_path, design_height, load_config, rnd,
                    save_config, widget_size)

TOKEN = re.compile(r"\{\{(x|y|f|c)(?::(\d+))?(\d?)\}\}")
BORDER = 10                      # design px of the white frame around the widget
COLS = (249, 265, 261)           # design widths of the three columns (sum + 2 * BORDER = 795)


def factors(width, height, design_h=DEFAULT_H):
    """Scale factors against the design size. design_h is 475 unless the server column has extra rows
    (see common.design_height): then everything is squeezed a little so it still fits the window."""
    sx, sy = width / DEFAULT_W, height / design_h
    return sx, sy, min(sx, sy)


def render_layout(template, width, height, design_h=DEFAULT_H):
    """Replace {{x:249}} {{y:50}} {{f:14}} (scaled numbers) and {{c1}} {{c2}} {{c3}} (column widths)."""
    sx, sy, sf = factors(width, height, design_h)
    border = rnd(BORDER * sf)
    c1, c2 = rnd(COLS[0] * sx), rnd(COLS[1] * sx)
    cols = {"1": c1, "2": c2, "3": width - 2 * border - c1 - c2}     # last column takes the rounding rest

    def one(m):
        kind, num, suffix = m.group(1), m.group(2), m.group(3)
        if kind == "c":
            return str(cols[suffix])
        return str(rnd(int(num) * {"x": sx, "y": sy, "f": sf}[kind]))

    # {{c1}}: the regex sees kind "c", no ":number", suffix "1"
    return TOKEN.sub(one, template)


def apply():
    cfg = load_config()
    if not config_path().exists():
        save_config(cfg)                      # first run: write a commented default config

    p = cfg["position"]
    anchor = p["anchor"] if p["anchor"] in ANCHORS else "top left"
    layer = p["layer"] if p["layer"] in LAYERS else "bottom"
    monitor = str(p["monitor"]).strip()
    monitor = monitor if monitor.lstrip("-").isdigit() else f'"{monitor}"'
    width, height = widget_size(cfg)
    design_h = design_height(cfg)

    (ROOT / "window.yuck").write_text(f""";; GENERATED by scripts/apply_config.py from config.toml - edit config.toml (or run `stats-widget config`), not this file.
(defwindow stats
  :monitor {monitor}
  :geometry (geometry :x "{int(p['x'])}px" :y "{int(p['y'])}px" :width "{width}px" :height "{height}px" :anchor "{anchor}")
  :stacking "{layer}"        ;; Wayland layer
  :exclusive false           ;; don't reserve screen space like a panel
  :focusable "none"          ;; never steal keyboard focus
  :namespace "stats-widget"
  :windowtype "desktop"      ;; X11 only
  :wm-ignore true            ;; X11 only
  (stats-widget))
""", encoding="utf-8")

    opacity = max(0, min(100, int(cfg["appearance"]["background_opacity"]))) / 100
    sx, sy, sf = factors(width, height, design_h)
    (ROOT / "theme.scss").write_text(
        "// GENERATED by scripts/apply_config.py - edit config.toml instead.\n"
        f"$bg-opacity: {opacity};\n"
        f"$sx: {sx:.6f};\n$sy: {sy:.6f};\n$sf: {sf:.6f};\n"
        f"$border: {rnd(BORDER * sf)}px;\n", encoding="utf-8")

    template = (ROOT / "eww.yuck.in").read_text(encoding="utf-8")
    (ROOT / "eww.yuck").write_text(
        ";; GENERATED from eww.yuck.in by scripts/apply_config.py - edit eww.yuck.in, not this file.\n"
        + render_layout(template, width, height, design_h), encoding="utf-8")


if __name__ == "__main__":
    apply()
